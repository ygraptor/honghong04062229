// 初始化文章数据（仅在数据库为空时执行）
export async function POST() {
  try {
    const client = getSupabaseClient();

    // 检查是否已有数据
    const { data: existing, error: checkError } = await client
      .from('blog_posts')
      .select('id')
      .limit(1);

    if (checkError) throw new Error(`检查失败: ${checkError.message}`);

    if (existing && existing.length > 0) {
      return NextResponse.json({ 
        message: '数据库已有文章数据，跳过初始化',
        count: existing.length 
      });
    }

    // 批量插入初始文章
    const { data, error } = await client
      .from('blog_posts')
      .insert(initialPosts)
      .select();

    if (error) throw new Error(`插入失败: ${error.message}`);

    return NextResponse.json({ 
      success: true, 
      message: '初始化文章成功',
      count: data?.length || 0,
      posts: data 
    });
  } catch (error) {
    console.error('Init blog error:', error);
    return NextResponse.json(
      { error: '初始化文章失败' },
      { status: 500 }
    );
  }
}
